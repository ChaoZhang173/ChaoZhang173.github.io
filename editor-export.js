/* Offline draft storage, previews, and portable ZIP exports. No network requests. */
(() => {
  'use strict';
  const encoder = new TextEncoder();
  const decoder = new TextDecoder();
  const MAX_FILE = 25 * 1024 * 1024;
  const MIME = {png:'image/png',jpg:'image/jpeg',jpeg:'image/jpeg',webp:'image/webp',gif:'image/gif',pdf:'application/pdf',svg:'image/svg+xml',html:'text/html',css:'text/css',js:'text/javascript',md:'text/markdown'};
  const clone = value => JSON.parse(JSON.stringify(value));
  const safePath = path => typeof path === 'string' && path.length < 240 && !path.startsWith('/') && !/[\\\x00-\x1f:]/.test(path) && !path.split('/').some(p => p === '..' || p === '.' || !p);
  const decode64 = value => Uint8Array.from(atob(value), c => c.charCodeAt(0));
  function encode64(bytes) {
    let text = '';
    for (let i=0; i<bytes.length; i+=32768) text += String.fromCharCode(...bytes.subarray(i,i+32768));
    return btoa(text);
  }
  const textAsset = (value,mime='text/javascript') => ({base64:encode64(encoder.encode(value)),mime});
  const baseFiles = () => window.EDITOR_BUNDLE?.files || {};
  const contentJS = data => '// Generated by the local homepage editor.\nwindow.SITE_CONTENT = ' + JSON.stringify(data,null,2).replace(/</g,'\\u003c') + ';\n';
  function referencedPaths(data) {
    const paths=new Set();
    const walk=value=>{if(typeof value==='string' && value.startsWith('assets/'))paths.add(value);else if(value && typeof value==='object')Object.values(value).forEach(walk);};
    walk(data);return paths;
  }
  function portableAssets(data,assets) {
    const result={};
    for(const path of referencedPaths(data)) {
      const asset=assets[path] || baseFiles()[path];
      if(asset && /^(image\/(png|jpeg|webp|gif)|application\/pdf)$/.test(asset.mime || ''))result[path]=asset;
    }
    return result;
  }
  function assertState(data, assets) {
    if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('内容格式不正确。');
    const object=value=>value && typeof value==='object' && !Array.isArray(value);
    if (!object(data.profile) || !object(data.intro) || !object(data.images)) throw new Error('这不是当前版本的网站草稿。');
    for(const key of ['lifeUpdates','academicActivities','researchProjects','publications','education','experience','researchSupport','computingResources','independentProjects']) {
      if(!Array.isArray(data[key]) || data[key].some(entry=>!object(entry)))throw new Error('栏目“'+key+'”格式不正确，请使用编辑器导出的备份。');
    }
    if(!Array.isArray(data.skills) || data.skills.some(s=>typeof s!=='string') || !Array.isArray(data.profile.focus) || data.profile.focus.some(s=>typeof s!=='string'))throw new Error('技能或研究方向格式不正确。');
    if (data.pageText !== undefined && (!object(data.pageText) || Object.values(data.pageText).some(value=>typeof value!=='string' && (!object(value) || Object.entries(value).some(([key,text])=>!['zh','en'].includes(key) || typeof text!=='string'))))) throw new Error('栏目标题与说明格式不正确。');
    if (data.defaultLanguage !== undefined && !['en','zh'].includes(data.defaultLanguage)) throw new Error('默认语言必须是英文或中文。');
    if (data.memorial !== undefined) {
      const memorial = data.memorial;
      const bilingual = value => object(value) && Object.entries(value).every(([key,text])=>['zh','en'].includes(key) && typeof text==='string');
      if (!object(memorial) || (memorial.enabled !== undefined && typeof memorial.enabled !== 'boolean') || ['title','text'].some(key=>memorial[key] !== undefined && !bilingual(memorial[key]))) throw new Error('纪念区域的标题或文字格式不正确。');
      if (memorial.image !== undefined && (!object(memorial.image) || (memorial.image.src !== undefined && typeof memorial.image.src !== 'string') || (memorial.image.alt !== undefined && !bilingual(memorial.image.alt)) || (memorial.image.fit !== undefined && !['contain','cover'].includes(memorial.image.fit)) || ['width','height'].some(key=>memorial.image[key] !== undefined && (!Number.isSafeInteger(memorial.image[key]) || memorial.image[key] <= 0)))) throw new Error('纪念区域的图片格式不正确。');
    }
    if (!assets || typeof assets !== 'object' || Array.isArray(assets)) throw new Error('附件格式不正确。');
    for (const [path,asset] of Object.entries(assets)) {
      if (!safePath(path) || !path.startsWith('assets/') || !asset || !/^(image\/(png|jpeg|webp|gif)|application\/pdf)$/.test(asset.mime || '')) throw new Error('附件路径或类型不受支持。');
      if (typeof asset.base64 !== 'string' || asset.base64.length > Math.ceil(MAX_FILE/3)*4+4 || !/^[A-Za-z0-9+/]*={0,2}$/.test(asset.base64)) throw new Error('附件格式错误或超过 25 MB。');
      try { atob(asset.base64); } catch (_) { throw new Error('附件内容无法读取。'); }
    }
  }
  let database;
  function openDatabase() {
    if (database) return database;
    database = new Promise((resolve,reject) => {
      let request;
      try { request = indexedDB.open('chao-homepage-editor',1); } catch (_) { reject(new Error('浏览器不允许保存本地草稿，请使用“备份草稿”下载文件。'));return; }
      request.onupgradeneeded = () => request.result.createObjectStore('drafts');
      request.onsuccess = () => { request.result.onversionchange = () => {request.result.close();database=null;}; resolve(request.result); };
      request.onerror = () => {database=null;reject(new Error('无法打开本地草稿，请使用“备份草稿”。'));};
      request.onblocked = () => {database=null;reject(new Error('请关闭其他编辑器标签页后重试，或先备份草稿。'));};
    });
    return database;
  }
  async function saveDraft(data,assets) {
    assertState(data,assets);
    const payload = {format:'chao-homepage-draft',version:1,savedAt:new Date().toISOString(),data:clone(data),assets:clone(portableAssets(data,assets))};
    const db = await openDatabase();
    return new Promise((resolve,reject) => {
      const tx=db.transaction('drafts','readwrite');
      tx.objectStore('drafts').put(payload,'current');
      tx.oncomplete=()=>resolve(payload.savedAt);
      tx.onerror=tx.onabort=()=>reject(new Error('草稿保存失败，可能是浏览器空间不足。请下载草稿备份。'));
    });
  }
  async function loadDraft() {
    const db=await openDatabase();
    return new Promise((resolve,reject)=>{
      const request=db.transaction('drafts','readonly').objectStore('drafts').get('current');
      request.onsuccess=()=>resolve(request.result || null);
      request.onerror=()=>reject(new Error('无法读取浏览器草稿，可以导入已下载的备份。'));
    });
  }
  async function imageDimensions(bytes,mime) {
    if (typeof Image === 'undefined' || typeof URL === 'undefined' || typeof URL.createObjectURL !== 'function') return {};
    // Browser decoding applies image orientation; use its displayed dimensions rather than raw EXIF pixels.
    return new Promise(resolve => {
      let image,objectURL,timer;
      let finished = false;
      const finish = dimensions => {
        if (finished) return;
        finished = true;
        clearTimeout(timer);
        if (image) image.onload = image.onerror = null;
        if (objectURL) URL.revokeObjectURL(objectURL);
        resolve(dimensions);
      };
      try {
        image = new Image();
        image.decoding = 'async';
        image.onload = () => {
          const width = image.naturalWidth, height = image.naturalHeight;
          finish(Number.isSafeInteger(width) && width > 0 && Number.isSafeInteger(height) && height > 0 ? {width,height} : {});
        };
        image.onerror = () => finish({});
        timer = setTimeout(() => finish({}),10000);
        objectURL = URL.createObjectURL(new Blob([bytes],{type:mime}));
        image.src = objectURL;
      } catch (_) {finish({});}
    });
  }
  async function readAsset(file,previousPath) {
    if (!file || file.size > MAX_FILE) throw new Error('请选择不超过 25 MB 的图片或 PDF。');
    const ext=(file.name.split('.').pop() || '').toLowerCase();
    if (!['png','jpg','jpeg','gif','webp','pdf'].includes(ext)) throw new Error('支持 JPG、PNG、WebP、GIF 图片和 PDF 简历。');
    const bytes=new Uint8Array(await file.arrayBuffer());
    const head=decoder.decode(bytes.subarray(0,12));
    const valid = ext==='pdf' ? head.startsWith('%PDF-') : ext==='png' ? bytes[0]===137 && bytes[1]===80 && bytes[2]===78 && bytes[3]===71 : ['jpg','jpeg'].includes(ext) ? bytes[0]===255 && bytes[1]===216 && bytes[2]===255 : ext==='gif' ? head.startsWith('GIF8') : head.startsWith('RIFF') && head.slice(8,12)==='WEBP';
    if (!valid) throw new Error('文件内容与扩展名不匹配，请选择原始图片或 PDF。');
    const id=crypto.randomUUID ? crypto.randomUUID() : Date.now().toString(36)+'-'+Math.random().toString(36).slice(2);
    const name=file.name.replace(/[^a-zA-Z0-9._-]/g,'_').slice(-80) || 'file.'+ext;
    const path=ext==='pdf' && safePath(previousPath) && previousPath.startsWith('assets/') && /\.pdf$/i.test(previousPath) ? previousPath : 'assets/uploads/'+id+'-'+name;
    const dimensions = ext === 'pdf' ? {} : await imageDimensions(bytes,MIME[ext]);
    return {path,asset:{base64:encode64(bytes),mime:MIME[ext]},...dimensions};
  }
  function assetURL(path,assets={}) {
    const asset=assets[path] || baseFiles()[path];
    if (asset) return 'data:'+asset.mime+';base64,'+asset.base64;
    return /^(https?:\/\/|data:image\/(png|jpeg|webp|gif);base64,)/i.test(path || '') ? path : '';
  }
  function download(blob,name) {
    const url=URL.createObjectURL(blob),a=document.createElement('a');
    a.href=url;a.download=name;document.body.append(a);a.click();a.remove();
    setTimeout(()=>URL.revokeObjectURL(url),60000);
    return name;
  }
  const stamp = () => new Date().toISOString().replace(/[-:]/g,'').slice(0,15).replace('T','-');
  async function downloadBackup(data,assets) {
    assertState(data,assets);
    const payload={format:'chao-homepage-draft',version:1,savedAt:new Date().toISOString(),data,assets:portableAssets(data,assets)};
    const blob=new Blob([JSON.stringify(payload)],{type:'application/json'});
    if(blob.size>200*1024*1024)throw new Error('草稿备份超过 200 MB，请减少照片体积后重试；也可以先下载完整网站。');
    return download(blob,'chao-homepage-draft-'+stamp()+'.json');
  }
  async function readBackup(file) {
    if (!file || file.size>200*1024*1024) throw new Error('备份文件太大或无法读取。');
    let payload;
    try { payload=JSON.parse(await file.text()); } catch (_) { throw new Error('备份文件无法读取，请选择从此编辑器下载的 JSON 备份。'); }
    if (payload.format!=='chao-homepage-draft' || payload.version!==1) throw new Error('这不是当前编辑器的草稿备份。');
    assertState(payload.data,payload.assets);
    return {data:payload.data,assets:payload.assets,savedAt:payload.savedAt};
  }
  const crcTable=Array.from({length:256},(_,n)=>{let c=n;for(let k=0;k<8;k++)c=(c&1)?0xedb88320^(c>>>1):c>>>1;return c>>>0;});
  function crc32(bytes) {let crc=0xffffffff;for(const b of bytes)crc=crcTable[(crc^b)&255]^(crc>>>8);return (crc^0xffffffff)>>>0;}
  function zipBytes(files) {
    const chunks=[],central=[];let offset=0,size=0;
    const now=new Date();const time=(now.getHours()<<11)|(now.getMinutes()<<5)|(now.getSeconds()>>1);const date=((Math.max(1980,now.getFullYear())-1980)<<9)|((now.getMonth()+1)<<5)|now.getDate();
    for(const [path,bytes] of Object.entries(files)) {
      if(!safePath(path))throw new Error('网站文件路径不正确。');
      const name=encoder.encode('chao-homepage/'+path),crc=crc32(bytes);
      const header=new Uint8Array(30),h=new DataView(header.buffer);
      h.setUint32(0,0x04034b50,true);h.setUint16(4,20,true);h.setUint16(6,0x0800,true);h.setUint16(10,time,true);h.setUint16(12,date,true);h.setUint32(14,crc,true);h.setUint32(18,bytes.length,true);h.setUint32(22,bytes.length,true);h.setUint16(26,name.length,true);
      chunks.push(header,name,bytes);
      const record=new Uint8Array(46),r=new DataView(record.buffer);
      r.setUint32(0,0x02014b50,true);r.setUint16(4,20,true);r.setUint16(6,20,true);r.setUint16(8,0x0800,true);r.setUint16(12,time,true);r.setUint16(14,date,true);r.setUint32(16,crc,true);r.setUint32(20,bytes.length,true);r.setUint32(24,bytes.length,true);r.setUint16(28,name.length,true);r.setUint32(42,offset,true);
      central.push(record,name);size+=record.length+name.length;offset+=header.length+name.length+bytes.length;
    }
    const count=Object.keys(files).length,end=new Uint8Array(22),e=new DataView(end.buffer);
    if(count>65535 || offset+size>0xffffffff)throw new Error('网站文件过多或过大，请减少图片后重试。');
    e.setUint32(0,0x06054b50,true);e.setUint16(8,count,true);e.setUint16(10,count,true);e.setUint32(12,size,true);e.setUint32(16,offset,true);
    return new Blob([...chunks,...central,end],{type:'application/zip'});
  }
  function buildFiles(data,assets) {
    assertState(data,assets);
    const templates=clone(baseFiles());
    if(!templates['index.html'] || !templates['editor.html'])throw new Error('编辑器文件不完整，请重新解压完整网站文件夹。');
    for(const [path,value] of Object.entries(assets)) templates[path]=value;
    const referenced=referencedPaths(data);
    for(const path of Object.keys(templates))if(path.startsWith('assets/uploads/') && !referenced.has(path))delete templates[path];
    // Rebuild the portable bundle without nesting a previous bundle inside it.
    delete templates['editor-bundle.js'];delete templates['content.js'];
    const files={};
    for(const [path,value] of Object.entries(templates))files[path]=decode64(value.base64);
    files['content.js']=encoder.encode(contentJS(data));
    files['editor-bundle.js']=encoder.encode('window.EDITOR_BUNDLE = '+JSON.stringify({version:1,files:templates})+';\n');
    return files;
  }
  async function exportSite(data,assets) {return download(zipBytes(buildFiles(data,assets)),'chao-homepage-'+stamp()+'.zip');}
  function previewNavigation(initialHash) {
    // srcdoc inherits editor.html as its base URL. Native #links would reload the
    // editor inside this frame, so resolve and scroll to the preview's own DOM.
    function jumpToSection(hash) {
      let id;
      try { id = decodeURIComponent(hash.slice(1)); } catch (_) { return; }
      const target = id ? document.getElementById(id) : document.body;
      if (!target) return;
      const padding = parseFloat(getComputedStyle(document.documentElement).scrollPaddingTop) || 0;
      const margin = parseFloat(getComputedStyle(target).scrollMarginTop) || 0;
      window.scrollTo({top: Math.max(0, window.scrollY + target.getBoundingClientRect().top - padding - margin), behavior:'auto'});
      return target;
    }
    document.addEventListener('click', event => {
      const link = event.target.closest('a');
      if (!link) return;
      const href = link.getAttribute('href') || '';
      if (href.startsWith('#')) {
        event.preventDefault();
        const target = jumpToSection(href);
        if (target && link.classList.contains('skip')) {
          target.setAttribute('tabindex','-1');
          target.focus({preventScroll:true});
        }
        return;
      }
      const match = /^(index|academic|projects|life)\.html(#.*)?$/.exec(href);
      if (match) {
        event.preventDefault();
        parent.postMessage({type:'chao-preview-navigation',page:match[1]+'.html',hash:match[2] || ''},'*');
      }
    });
    if (initialHash) requestAnimationFrame(() => jumpToSection(initialHash));
  }
  async function preview(data,assets,page='index.html') {
    assertState(data,assets);
    const [name,fragment]=page.split('#');
    if(!['index.html','academic.html','projects.html','life.html'].includes(name))throw new Error('未知的预览页面。');
    const files=baseFiles();
    const read=path=>{if(!files[path])throw new Error('缺少预览所需文件：'+path);return decoder.decode(decode64(files[path].base64));};
    const state=clone(data);
    const inlineAssets=value=>{
      for(const [key,item] of Object.entries(value || {})) {
        if(['src','url','resume'].includes(key) && typeof item==='string' && item.startsWith('assets/')) value[key]=assetURL(item,assets) || item;
        else if(item && typeof item==='object')inlineAssets(item);
      }
    };
    inlineAssets(state);
    let html=read(name).replace(/<script\b[^>]*src=["'](?:content|script)\.js["'][^>]*>\s*<\/script>/gi,'').replace(/<link\b[^>]*href=["']style\.css["'][^>]*>/gi,'');
    const escapeScript=source=>source.replace(/<\/script/gi,'<\\/script');
    const style=read('style.css').replace(/<\/style/gi,'<\\/style');
    html=html.replace('</head>','<style>'+style+'</style></head>');
    html=html.replace('href="assets/favicon.svg"','href="'+assetURL('assets/favicon.svg',assets)+'"');
    const navigation='('+previewNavigation.toString()+')('+JSON.stringify(fragment ? '#'+fragment : '').replace(/</g,'\\u003c')+');';
    return html.replace('</body>','<script>'+escapeScript(contentJS(state))+'</script><script>'+escapeScript(read('script.js'))+'</script><script>'+escapeScript(navigation)+'</script></body>');
  }
  window.EditorIO={loadDraft,saveDraft,readAsset,assetURL,downloadBackup,readBackup,exportSite,preview};
  // Pure functions used for archive verification without driving the browser UI.
  if (typeof module!=='undefined' && module.exports) module.exports={buildFiles,zipBytes,contentJS,assertState};
})();
