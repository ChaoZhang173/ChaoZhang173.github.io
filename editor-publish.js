/* Direct GitHub publishing. Credentials stay in this closure, never in drafts. */
(() => {
  'use strict';
  const REPO='ChaoZhang173/ChaoZhang173.github.io';
  const SITE='https://chaozhang173.github.io/';
  const API='https://api.github.com';
  const encoder=new TextEncoder(),decoder=new TextDecoder();
  const equal=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
  const contentJS=data=>'// Generated by the local homepage editor.\nwindow.SITE_CONTENT = '+JSON.stringify(data,null,2).replace(/</g,'\\u003c')+';\n';
  function parseContent(source) {
    const match=/^(?:\s*\/\/[^\n]*(?:\n|$))*\s*window\.SITE_CONTENT\s*=\s*([\s\S]*);\s*$/.exec(source);
    if(!match)throw new Error('线上内容格式无法识别，请保留草稿后联系维护者。');
    return JSON.parse(match[1]);
  }
  function createPublisher({fetchImpl=globalThis.fetch,cryptoImpl=globalThis.crypto,sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms))}={}) {
    let token='',account='',connectedAssets=null,locked=false;
    async function request(path,{method='GET',body,anonymous=false}={}) {
      const headers={Accept:'application/vnd.github+json','X-GitHub-Api-Version':'2026-03-10'};
      if(token && !anonymous)headers.Authorization='Bearer '+token;
      if(body!==undefined)headers['Content-Type']='application/json';
      let response;
      try {
        response=await fetchImpl(API+path,{method,headers,body:body===undefined?undefined:JSON.stringify(body),credentials:'omit',redirect:'error',cache:'no-store',signal:AbortSignal.timeout(45000)});
      } catch (_) {
        const error=new Error('GitHub 暂时无法连接。当前修改仍在编辑器中，请稍后重试。');error.code='NETWORK';throw error;
      }
      if(!response.ok) {
        if(response.status===403 && response.headers?.get('x-ratelimit-remaining')==='0')throw new Error('GitHub 暂时限制了访问次数，请稍后重试。当前修改仍在编辑器中。');
        const descriptions={401:'授权码无效或已过期，请重新连接 GitHub。',403:'GitHub 拒绝了请求。请确认此授权码只选中了主页仓库，且 Contents 为 Read and write；请求过多时请稍后重试。',404:'无法访问主页仓库，请检查授权码的仓库选择。',409:'仓库版本发生冲突，请先载入线上最新内容。',422:'线上版本已变化或 GitHub 拒绝了这次更新。请检查线上内容后重试。'};
        const error=new Error(descriptions[response.status] || 'GitHub 暂时未能完成请求，请保留草稿后重试。');error.status=response.status;throw error;
      }
      return response.status===204 ? null : response.json();
    }
    const repositoryPath='/repos/'+REPO;
    const sha=value=>{if(!/^[a-f0-9]{40}$/.test(value || ''))throw new Error('GitHub 返回了无法识别的文件版本。');return value;};
    async function snapshot() {
      const ref=await request(repositoryPath+'/git/ref/heads/main');
      const head=sha(ref.object?.sha);
      const commit=await request(repositoryPath+'/git/commits/'+head);
      const treeSHA=sha(commit.tree?.sha);
      const tree=await request(repositoryPath+'/git/trees/'+treeSHA+'?recursive=1');
      if(tree.truncated)throw new Error('仓库文件列表不完整，本次没有发布。');
      const files=new Map(tree.tree.filter(entry=>entry.type==='blob').map(entry=>[entry.path,entry.sha]));
      if(!files.has('content.js'))throw new Error('主页仓库中缺少 content.js，本次没有发布。');
      const blob=await request(repositoryPath+'/git/blobs/'+sha(files.get('content.js')));
      if(blob.encoding!=='base64')throw new Error('无法读取线上内容。');
      const source=decoder.decode(Uint8Array.from(atob(blob.content.replace(/\s/g,'')),c=>c.charCodeAt(0)));
      return {head,treeSHA,files,data:parseContent(source)};
    }
    async function latestContent() {
      if(!account) {
        const response=await fetchImpl(SITE+'content.js?editor='+Date.now(),{cache:'no-store',credentials:'omit',redirect:'error',signal:AbortSignal.timeout(30000)});
        if(!response.ok)throw new Error('暂时无法读取线上内容，请保留当前修改后稍后重试。');
        return parseContent(await response.text());
      }
      const remote=await snapshot();
      if(account)connectedAssets=remote.files;
      return remote.data;
    }
    function disconnect() {token='';account='';connectedAssets=null;}
    async function connect(value,baseline) {
      disconnect();
      if(!/^github_pat_[A-Za-z0-9_]+$/.test(value.trim()))throw new Error('请使用 GitHub 的 Fine-grained personal access token，通常以 github_pat_ 开头。');
      token=value.trim();
      try {
        const user=await request('/user');
        if(user.login?.toLowerCase()!=='chaozhang173')throw new Error('请使用 ChaoZhang173 账号的授权码。');
        const repo=await request(repositoryPath);
        if(repo.full_name?.toLowerCase()!==REPO.toLowerCase() || !repo.permissions?.push)throw new Error('当前账号没有更新主页仓库的权限。');
        const remote=await snapshot();
        if(!equal(remote.data,baseline))throw new Error('线上内容比当前编辑器更新。请先备份当前修改，再点击“载入线上最新内容”后连接。');
        connectedAssets=remote.files;account=user.login;
        return {login:account};
      } catch(error) {disconnect();throw error;}
    }
    async function blobSHA(bytes) {
      const header=encoder.encode('blob '+bytes.length+'\0');
      const buffer=new Uint8Array(header.length+bytes.length);buffer.set(header);buffer.set(bytes,header.length);
      return Array.from(new Uint8Array(await cryptoImpl.subtle.digest('SHA-1',buffer)),b=>b.toString(16).padStart(2,'0')).join('');
    }
    function references(data) {
      const result=new Set();
      function walk(value) {
        if(typeof value==='string' && value.startsWith('assets/'))result.add(value);
        else if(value && typeof value==='object')Object.values(value).forEach(walk);
      }
      walk(data);return result;
    }
    async function publish({data,assets,baseline},progress=()=>{}) {
      if(!account || !token)throw new Error('请先连接 GitHub。');
      if(locked)throw new Error('已有一次发布正在进行，请稍候。');
      locked=true;
      try {
        progress('正在检查线上版本…');
        const remote=await snapshot(),source=contentJS(data),contentHash=await blobSHA(encoder.encode(source));
        const needed=references(data),uploads=[];
        for(const path of needed) {
          if(!/^assets\/[A-Za-z0-9_./-]+$/.test(path) || path.split('/').some(p=>p==='..' || p==='.' || !p))throw new Error('图片或简历路径不正确，本次没有发布。');
          const asset=assets[path];
          if(!asset) {
            if(!remote.files.has(path))throw new Error('线上找不到图片或简历：'+path+'。请重新选择这个文件。');
            continue;
          }
          if(!/^(image\/(png|jpeg|webp|gif)|application\/pdf)$/.test(asset.mime || '') || typeof asset.base64!=='string' || asset.base64.length>35*1024*1024)throw new Error('附件类型或大小不正确。');
          const bytes=Uint8Array.from(atob(asset.base64),c=>c.charCodeAt(0));
          const hash=await blobSHA(bytes);
          if(remote.files.get(path)!==hash)uploads.push({path,base64:asset.base64,hash});
        }
        // An identical retry is a no-op, including when a previous acknowledgement was lost.
        if(equal(remote.data,data) && uploads.length===0) {
          connectedAssets=remote.files;
          return {sha:remote.head,source,noChange:true};
        }
        if(!equal(remote.data,baseline))throw new Error('线上内容已被其他页面或设备更新。本次没有覆盖它；请备份当前修改，再载入线上最新内容合并。');
        for(const file of uploads) {
          if(connectedAssets?.get(file.path)!==remote.files.get(file.path))throw new Error('图片或简历已在其他地方更新，本次没有覆盖它。请重新连接并核对最新版本。');
        }
        const entries=[];
        if(remote.files.get('content.js')!==contentHash)entries.push({path:'content.js',mode:'100644',type:'blob',content:source});
        for(let i=0;i<uploads.length;i++) {
          progress('正在上传照片或简历 '+(i+1)+' / '+uploads.length+'…');
          const file=uploads[i];
          const blob=await request(repositoryPath+'/git/blobs',{method:'POST',body:{content:file.base64,encoding:'base64'}});
          if(sha(blob.sha)!==file.hash)throw new Error('文件上传校验未通过，本次没有发布。');
          entries.push({path:file.path,mode:'100644',type:'blob',sha:blob.sha});
        }
        progress('正在提交网站内容…');
        const tree=await request(repositoryPath+'/git/trees',{method:'POST',body:{base_tree:remote.treeSHA,tree:entries}});
        const commit=await request(repositoryPath+'/git/commits',{method:'POST',body:{message:'Update homepage from web editor',tree:sha(tree.sha),parents:[remote.head]}});
        const committed=sha(commit.sha);
        // Never force: a racing writer makes this fail rather than overwrite their commit.
        try {await request(repositoryPath+'/git/refs/heads/main',{method:'PATCH',body:{sha:committed,force:false}});}
        catch(error) {
          let confirmed=false;
          try {confirmed=(await request(repositoryPath+'/git/ref/heads/main')).object?.sha===committed;} catch(_) {}
          if(!confirmed) {
            if(error.code==='NETWORK' || error.status>=500)throw new Error('提交结果暂时无法确认。当前修改仍保留；再次发布会先检查线上内容，避免重复提交。也可以先查看 GitHub 仓库。');
            throw error;
          }
        }
        connectedAssets=new Map(remote.files);
        connectedAssets.set('content.js',contentHash);
        for(const file of uploads)connectedAssets.set(file.path,file.hash);
        return {sha:committed,source,noChange:false};
      } finally {locked=false;}
    }
    async function waitForLive(receipt,progress=()=>{},attempts=18) {
      for(let i=0;i<attempts;i++) {
        try {
          const response=await fetchImpl(SITE+'content.js?published='+receipt.sha,{cache:'no-store',credentials:'omit',redirect:'error',signal:AbortSignal.timeout(12000)});
          if(response.ok && equal(parseContent(await response.text()),parseContent(receipt.source)))return true;
        } catch(_) {}
        progress('已提交到 GitHub，正在等待主页更新…');
        if(i+1<attempts)await sleep(5000);
      }
      return false;
    }
    return {connect,disconnect,isConnected:()=>Boolean(account && token),latestContent,publish,waitForLive,site:SITE,repository:'https://github.com/'+REPO};
  }
  if(typeof window!=='undefined')window.EditorPublisher=createPublisher();
  if(typeof module!=='undefined' && module.exports)module.exports={createPublisher,parseContent,contentJS};
})();
